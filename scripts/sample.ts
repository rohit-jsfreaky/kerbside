// The sample: Wexford Bus's GTFS feed from Transport for Ireland (National Transport Authority, CC BY 4.0), with
// shapes.txt and translations.txt left out to keep it small: public/samples/wexford-bus.zip. Writes docs/sample.json
// and templates/_shared/example.ts for Wexford Bus Station (the busiest stop), the week of 23 November 2026.
// Run: node --experimental-strip-types scripts/sample.ts [path/to/GTFS_Wexford_Bus.zip]
import { readFileSync, writeFileSync } from "node:fs";
import { strFromU8, unzipSync, zipSync } from "fflate";
import { busyStops, readFeed, toValues } from "../templates/_shared/gtfs.ts";
import { SAMPLE } from "../src/lib/sample.ts";

const out = new URL("../public/samples/wexford-bus.zip", import.meta.url);
if (process.argv[2]) {
  const all = unzipSync(readFileSync(process.argv[2]));
  delete all["shapes.txt"];
  delete all["translations.txt"];
  writeFileSync(out, zipSync(all, { level: 9 }));
}
const files = Object.fromEntries(Object.entries(unzipSync(readFileSync(out))).map(([k, v]) => [k, strFromU8(v)]));
const feed = readFeed(files);
const stop = busyStops(feed).find((s) => s.stop.name === SAMPLE.stopName)!.stop;
const v = toValues(feed, stop.id, SAMPLE.lines, { monday: SAMPLE.monday, date: "2026-11-22", note: SAMPLE.note, source: SAMPLE.source });
const json = JSON.stringify(v, null, 2);
writeFileSync(new URL("../docs/sample.json", import.meta.url), `${json}\n`);
writeFileSync(new URL("../templates/_shared/example.ts", import.meta.url), `// The sample: Wexford Bus Station from Wexford Bus's GTFS feed (NTA, CC BY 4.0), week of 23 November 2026.\n// Generated by scripts/sample.ts.\nconst example = ${json};\n\nexport default example;\n`);
console.log(stop, v.lines.map((l) => `${l.route} → ${l.headsign}: ${l.weekday}/${l.saturday}/${l.sunday} ${l.notes.map((n) => `${n.mark}=${n.text}`).join(" ")}`).join("\n"));
